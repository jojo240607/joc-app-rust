"""
生成 src/sensors/sim/dataset_data.rs —— 虚拟传感器回放数据集。

默认：生成一段"真实形态"的机动飞行合成片段（起飞→悬停→小幅机动→下降→落地），
      加速度/角速度/气压高度/GPS/RC 量级贴近真实四旋翼，确定性可复现。

真实数据注入（在你有外网 + 对应解析库的机器上运行）：
  python tools/gen_dataset.py --bin  path/to/flashlog.BIN   # ArduPilot，需 pip install pymavlink
  python tools/gen_dataset.py --ulg  path/to/log.ulg        # PX4，需 pip install pyulog
  python tools/gen_dataset.py --csv  path/to/telemetry.csv  # 见 --csv-cols 说明
  python tools/gen_dataset.py --hz 50 --seconds 20          # 调整采样率/时长

输出格式：pub static DATASET_FRAMES: [Frame; N] = [ Frame{...}, ... ];
         Frame 字段见 src/sensors/dataset.rs。
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "sensors", "sim", "dataset_data.rs")

# 起点经纬度（随便选一个真实坐标，仅用于 GPS 位移相对量）
LAT0 = 37.4275
LON0 = -122.1697
METERS_PER_DEG_LAT = 111320.0
METERS_PER_DEG_LON = 111320.0 * math.cos(math.radians(LAT0))


def fmt_f32(x):
    # 保证是合法 f32 字面量（整数需写成 x.0，否则 Rust 推断为 integer）
    s = "%.6g" % x
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s


def synth_frame(i, hz):
    """生成第 i 帧（真实形态合成）。返回 Frame 各字段列表。

    关键：IMU 加速度与各观测量（气压/GPS 高度、水平位置）保持运动学自洽——
    即 alt(t) 的二阶导数等于 (az - 9.81)，pos(t) 的二阶导数等于 (ax, ay)。
    这样 IMU 双重积分能精确重建高度/位置，EKF 不会因积分漂移而发散，
    飞控估计状态保持健康（crit=false）。
    """
    t = i / hz

    # 温和稳定的悬停 + 小幅姿态/轨迹机动剖面（全程在空中的一段真实巡航）。
    w_h = 2 * math.pi * 0.05      # 高度振荡 0.05 Hz
    w_rp = 2 * math.pi * 0.12     # 姿态机动频率
    w_yaw = 2 * math.pi * 0.07
    w_pos = 2 * math.pi * 0.03    # 水平轨迹机动频率

    # ---- 高度（气压 + GPS 高度一致），有界振荡，IMU 积分可重建 ----
    alt = 10.0 + 2.0 * math.sin(w_h * t)
    a_alt = -2.0 * w_h * w_h * math.sin(w_h * t)   # alt 二阶导
    az = 9.81 + a_alt                               # 机体 z 含重力

    # ---- 姿态机动（小角度）----
    roll_cmd = 0.10 * math.sin(w_rp * t)
    pitch_cmd = 0.08 * math.sin(w_rp * t + 1.0)
    yaw_rate = 0.05 * math.sin(w_yaw * t)

    # ---- 水平位置（有界，避免积分漂移）----
    north = 15.0 * math.sin(w_pos * t)
    east = 8.0 * math.sin(w_pos * t + 0.6)
    a_north = -15.0 * w_pos * w_pos * math.sin(w_pos * t)
    a_east = -8.0 * w_pos * w_pos * math.sin(w_pos * t + 0.6)

    # ---- 加速度（机体系，含重力；小角度近似 a_body ≈ R*a_world）----
    # 水平机动主要来自姿态倾斜：a ≈ g*[pitch, -roll]
    ax = 9.81 * pitch_cmd + a_north + 0.03 * math.sin(2 * math.pi * 0.9 * t)
    ay = -9.81 * roll_cmd + a_east + 0.03 * math.sin(2 * math.pi * 0.8 * t + 0.5)
    az += 0.03 * math.sin(2 * math.pi * 1.1 * t + 1.3)

    # ---- 角速度 ----
    gx = 0.08 * math.cos(w_rp * t + 1.0)   # pitch 速率
    gy = -0.10 * math.cos(w_rp * t)        # roll 速率
    gz = yaw_rate
    gx += 0.004 * math.sin(2 * math.pi * 13.0 * t)
    gy += 0.004 * math.sin(2 * math.pi * 17.0 * t + 0.3)
    gz += 0.003 * math.sin(2 * math.pi * 11.0 * t + 0.7)

    # ---- GPS（经纬度由水平 NED 位移换算）----
    lat = LAT0 + (north) / METERS_PER_DEG_LAT
    lon = LON0 + (east) / METERS_PER_DEG_LON

    # ---- RC 摇杆（悬停油门 ~0.6，叠加姿态指令与偏航）----
    throttle = 0.60 + 0.02 * math.sin(w_h * t)
    rc = [
        max(0.0, min(1.0, throttle)),
        roll_cmd / 0.3,
        pitch_cmd / 0.3,
        yaw_rate / 0.2,
        0.0,              # aux1 空闲
    ]

    return {
        "imu_accel": [ax, ay, az],
        "imu_gyro": [gx, gy, gz],
        "baro_alt": alt,
        "gps": [lat, lon, alt],
        "rc": rc,
    }


def emit_synth(hz, seconds):
    n = int(hz * seconds)
    lines = []
    lines.append("// AUTO-GENERATED by tools/gen_dataset.py (synth mode). DO NOT EDIT.")
    lines.append("// Realistic maneuver segment: takeoff -> hover w/ maneuver -> descend -> land.")
    lines.append("// Override with --bin/--ulg/--csv to inject a real flight log.")
    lines.append("pub static DATASET_FRAMES: [Frame; %d] = [" % n)
    for i in range(n):
        f = synth_frame(i, hz)
        a = ", ".join(fmt_f32(x) for x in f["imu_accel"])
        g = ", ".join(fmt_f32(x) for x in f["imu_gyro"])
        gp = ", ".join(fmt_f32(x) for x in f["gps"])
        r = ", ".join(fmt_f32(x) for x in f["rc"])
        lines.append(
            "    Frame { imu_accel: [%s], imu_gyro: [%s], baro_alt: %s, gps: [%s], rc: [%s] },"
            % (a, g, fmt_f32(f["baro_alt"]), gp, r)
        )
    lines.append("];")
    return "\n".join(lines) + "\n"


