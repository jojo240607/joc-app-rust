def main():
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("--bin", help="ArduPilot .BIN 真实日志")
    p.add_argument("--ulg", help="PX4 .ulg 真实日志")
    p.add_argument("--csv", help="CSV 真实遥测")
    p.add_argument("--csv-cols",
                   help="CSV 列名映射 accel_x,accel_y,accel_z,gyro_x,gyro_y,gyro_z,"
                        "baro_alt,gps_lat,gps_lon,gps_alt,rc_thr,rc_roll,rc_pitch,rc_yaw,rc_aux")
    p.add_argument("--hz", type=int, default=50)
    p.add_argument("--seconds", type=float, default=20.0)
    p.add_argument("--out", default=OUT)
    args = p.parse_args()

    if args.bin:
        src = emit_from_bin(args.bin, args.hz, args.seconds)
    elif args.ulg:
        src = emit_from_ulg(args.ulg, args.hz, args.seconds)
    elif args.csv:
        src = emit_from_csv(args.csv, args.hz, args.seconds, args.csv_cols)
    else:
        src = emit_synth(args.hz, args.seconds)

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(src)
    print("wrote", args.out, "(%d bytes)" % len(src))


if __name__ == "__main__":
    main()
